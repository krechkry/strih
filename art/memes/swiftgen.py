"""memes.json -> MemeArt.swift (the layer data the app draws)."""
import json, sys

CASES = {
    "02_camera_grin": "cameraGrin", "03_shocked": "shocked",
    "04_explosion_cat": "explosionCat", "05_investigating": "investigating", "06_train_duo": "trainDuo",
    "07_smug_cat": "smugCat", "08_nerd_cat": "nerdCat", "09_ipod_float": "ipodFloat",
    "10_absolute_cinema": "absoluteCinema", "11_deadpan": "deadpan", "12_suspicious": "suspicious",
    "14_thumbs_up_cat": "thumbsUpCat",
}

def num(v):
    v = float(v)
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"

def motion(a):
    t = a["t"]
    if t == "rot":
        return f'.rot(deg: {num(a["a"])}, period: {num(a["p"])}, phase: {num(a["ph"])}, x: {num(a["x"])}, y: {num(a["y"])})'
    if t == "move":
        return f'.move(dx: {num(a["dx"])}, dy: {num(a["dy"])}, period: {num(a["p"])}, phase: {num(a["ph"])})'
    if t == "scale":
        return f'.scale(sx: {num(a["sx"])}, sy: {num(a["sy"])}, period: {num(a["p"])}, phase: {num(a["ph"])}, x: {num(a["x"])}, y: {num(a["y"])})'
    if t == "shake":
        return f'.shake(amp: {num(a["a"])}, hz: {num(a["f"])})'
    if t == "flash":
        return f'.flash(period: {num(a["p"])}, on: {num(a["on"])}, phase: {num(a["ph"])})'
    raise ValueError(t)

def main(src, dst):
    data = json.load(open(src))
    assert set(data) == set(CASES), set(data) ^ set(CASES)
    out = [
        "// Generated by art/memes/swiftgen.py from art/memes/layers.py. Do not edit by hand:",
        "// change layers.py, then run art/memes/build.sh.",
        "import CoreGraphics",
        "",
        "extension Meme {",
        "    /// The layers back to front, in a 480 x 480 artboard.",
        "    var specs: [MemeLayer.Spec] {",
        "        switch self {",
    ]
    for key in sorted(data):
        out.append(f"        case .{CASES[key]}:")
        out.append("            return [")
        for lay in data[key]:
            for ch in lay["d"] + lay.get("gap", ""):
                assert ch in "MLQZ0123456789.- ", repr(ch)
            gap = f'"{lay["gap"]}"' if "gap" in lay else "nil"
            mots = "[" + ", ".join(motion(a) for a in lay.get("anims", [])) + "]"
            eyes = "[" + ", ".join(f"MemeEye(x: {num(e[0])}, y: {num(e[1])}, rx: {num(e[2])}, ry: {num(e[3])})" for e in lay.get("eyes", [])) + "]"
            blink = (f'MemeBlink(period: {num(lay["blink"][0])}, phase: {num(lay["blink"][1])}, length: {num(lay["blink"][2])})'
                     if "blink" in lay else "nil")
            out.append("                MemeLayer.Spec(")
            out.append(f'                    path: "{lay["d"]}",')
            out.append(f"                    gap: {gap},")
            out.append(f"                    motions: {mots},")
            out.append(f"                    eyes: {eyes},")
            out.append(f"                    blink: {blink},")
            if "mouth" in lay:
                m = lay["mouth"]
                keys = ["x", "y", "half", "flat", "smile", "liftLeft", "liftRight", "widen", "shift", "width", "lipY", "lipHalf", "lipSag", "lipWidth", "openFrom", "dimpleFrom"]
                out.append("                    mouth: MemeMouth(" + ", ".join(f"{k}: {num(m[k])}" for k in keys) + ")")
            else:
                out.append("                    mouth: nil")
            out.append("                ),")
        out.append("            ]")
    out += ["        }", "    }", "}", ""]
    open(dst, "w").write("\n".join(out))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
